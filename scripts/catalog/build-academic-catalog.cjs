const fs = require('node:fs');
const crypto = require('node:crypto');
const input = process.argv[2] ?? '.nx/yks2026.json';
const raw = fs.readFileSync(input),
  hash = crypto.createHash('sha256').update(raw).digest('hex');
const expected = '92a773116f7a57a6c1bfde3111f059c1f68387f7f6b8b0651920a3735740c8a6';
if (hash !== expected) throw Error('Source snapshot changed. Review before importing a new catalog.');
const source = JSON.parse(raw),
  campuses = JSON.parse(fs.readFileSync('data/academic/campuses.tr.json', 'utf8'));
const key = (s) =>
  s
    .toLocaleLowerCase('tr')
    .normalize('NFD')
    .replace(/\p{M}/gu, '')
    .replaceAll('ı', 'i')
    .replace(/\s+/g, ' ')
    .trim();
const title = (s) =>
  s
    .replace(/\s*\([^)]*\)\s*$/, '')
    .toLocaleLowerCase('tr')
    .replace(/(^|[\s-])(\p{L})/gu, (_, space, letter) => space + letter.toLocaleUpperCase('tr'))
    .replace(/^Tobb /, 'TOBB ');
const clean = (s) =>
  s
    .replace(/\s*\((?:Burslu|Ücretli|%\s*\d+(?:[,.]\d+)? İndirimli|İÖ|İkinci Öğretim)\)/giu, '')
    .replace(/\s+/g, ' ')
    .trim();
const universities = source.unis
  .flatMap(([name, type], index) => {
    if (!['Devlet', 'Vakıf'].includes(type)) return [];
    const label = title(name);
    const departments = [
      ...new Set(
        source.rows
          .filter((row) => row[2] === index)
          .map((row) => clean(row[4]))
          .filter((n) => n && n.length <= 150),
      ),
    ].sort((a, b) => a.localeCompare(b, 'tr'));
    const entry = campuses.find((row) => key(row.university) === key(label));
    return [
      { name: label, departments, campuses: entry?.campuses ?? [], campus_source: entry?.source ?? null },
    ];
  })
  .sort((a, b) => a.name.localeCompare(b.name, 'tr'));
for (const entry of campuses)
  if (!universities.some((row) => key(row.name) === key(entry.university)))
    throw Error('Unknown university in campus sources: ' + entry.university);
const snapshot = {
  version: '2026102203',
  retrieved_on: '2026-10-22',
  program_source: 'https://github.com/YVZO/yks2026/blob/main/data.json',
  source_sha256: hash,
  universities,
};
fs.writeFileSync('data/academic/catalog.tr.json', JSON.stringify(snapshot, null, 2) + '\n');
const catalogJson = JSON.stringify(snapshot);
if (catalogJson.includes('$catalog$') || catalogJson.includes('$seed$'))
  throw Error('Unexpected SQL delimiter in catalog data');
const sql = `-- Generated by scripts/catalog/build-academic-catalog.cjs. Source and campus provenance are in data/academic/catalog.tr.json.
-- Run the WHOLE file after SQL 30. Add/update catalog approval only; never delete or rename existing rows or profile references.
-- Program list is a source snapshot, not official student-status verification. Campus coverage is explicitly partial.
-- Self-contained atomic block: no temporary table or connection/session dependency.
do $seed$
declare
 catalog constant jsonb := $catalog$${catalogJson}$catalog$::jsonb;
 item jsonb; uni uuid; program_source text;
begin
 perform set_config('lock_timeout','5s',true);
 lock table public.universities,public.campuses,public.departments in share row exclusive mode;
 program_source := catalog->>'program_source';
 for item in select value from jsonb_array_elements(catalog->'universities') loop
  insert into public.universities(name,catalog_verified,catalog_source) values(item->>'name',true,program_source)
    on conflict(name_key) do update set catalog_verified=true,catalog_source=excluded.catalog_source;
  select id into uni from public.universities where name_key=private.kx_key(item->>'name');
  if uni is null then raise exception 'Catalog normalization contract missing'; end if;
  insert into public.departments(university_id,name,catalog_verified,catalog_source)
    select distinct on(private.kx_key(value)) uni,value,true,program_source from jsonb_array_elements_text(item->'departments') order by private.kx_key(value),value
    on conflict(university_id,name_key) do update set catalog_verified=true,catalog_source=excluded.catalog_source;
  insert into public.campuses(university_id,name,catalog_verified,catalog_source)
    select distinct on(private.kx_key(value)) uni,value,true,item->>'campus_source' from jsonb_array_elements_text(item->'campuses') order by private.kx_key(value),value
    on conflict(university_id,name_key) do update set catalog_verified=true,catalog_source=excluded.catalog_source;
 end loop;
 perform pg_notify('pgrst','reload schema');
end $seed$;
select '2026102203'::text as catalog_version,
 (select count(*) from public.universities where catalog_verified) as universities,
 (select count(*) from public.departments where catalog_verified) as departments,
 (select count(*) from public.campuses where catalog_verified) as campuses,
 (select count(distinct university_id) from public.campuses where catalog_verified) as universities_with_campuses;
-- END OF FILE: 2026102203
`;
fs.writeFileSync('docs/supabase/31-academic-catalog-seed.sql', sql);
