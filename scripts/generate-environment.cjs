const fs = require('node:fs');
const path = require('node:path');

const VARIABLE_NAMES = ['SUPABASE_URL', 'SUPABASE_PUBLISHABLE_KEY'];
const GENERATED_PATH = 'apps/shell/src/environments/environment.ts';

function readLocalEnvironment(filePath) {
  if (!fs.existsSync(filePath)) return {};
  const result = {};
  for (const rawLine of fs.readFileSync(filePath, 'utf8').split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const match = /^(?:export\s+)?([A-Z_][A-Z0-9_]*)\s*=\s*(.*)$/.exec(line);
    if (!match || !VARIABLE_NAMES.includes(match[1])) continue;
    let value = match[2].trim();
    if (value.startsWith('"') || value.startsWith("'")) {
      const quote = value[0];
      const end = value.lastIndexOf(quote);
      if (end === 0 || !/^(?:\s*#.*)?$/.test(value.slice(end + 1))) {
        throw new Error(`Invalid .env.local entry for ${match[1]}.`);
      }
      value = value.slice(1, end);
    } else {
      value = value.split(/\s+#/)[0].trim();
    }
    result[match[1]] = value;
  }
  return result;
}

function validateUrl(value) {
  let url;
  try {
    url = new URL(value);
  } catch {
    throw new Error('SUPABASE_URL must be a valid HTTPS project URL.');
  }
  const localHost = ['localhost', '127.0.0.1', '[::1]'].includes(url.hostname);
  if (
    (url.protocol !== 'https:' && !(url.protocol === 'http:' && localHost)) ||
    url.username ||
    url.password ||
    url.search ||
    url.hash ||
    url.pathname !== '/'
  ) {
    throw new Error('SUPABASE_URL must be an HTTPS origin, or an HTTP localhost origin.');
  }
  return url.origin;
}

function validatePublishableKey(value) {
  if (/^sb_publishable_[A-Za-z0-9_-]+$/.test(value)) return value;
  if (value.startsWith('sb_secret_')) {
    throw new Error('SUPABASE_PUBLISHABLE_KEY cannot contain a secret key.');
  }
  const parts = value.split('.');
  if (parts.length === 3 && parts.every((part) => /^[A-Za-z0-9_-]+$/.test(part))) {
    try {
      const payload = JSON.parse(Buffer.from(parts[1], 'base64url').toString('utf8'));
      if (payload.role === 'anon') return value;
      if (payload.role === 'service_role') {
        throw new Error('SUPABASE_PUBLISHABLE_KEY cannot contain a service_role key.');
      }
    } catch (error) {
      if (error.message.includes('service_role')) throw error;
    }
  }
  throw new Error('SUPABASE_PUBLISHABLE_KEY must be a publishable key or legacy anon key.');
}

function resolveEnvironment(environment, local = {}, strict = false) {
  const values = Object.fromEntries(
    VARIABLE_NAMES.map((name) => [name, String(environment[name] ?? local[name] ?? '').trim()]),
  );
  const hasUrl = Boolean(values.SUPABASE_URL);
  const hasKey = Boolean(values.SUPABASE_PUBLISHABLE_KEY);
  if (!hasUrl && !hasKey && !strict) {
    return { supabaseUrl: '', supabasePublishableKey: '' };
  }
  if (!hasUrl || !hasKey) {
    const missing = VARIABLE_NAMES.filter((name) => !values[name]);
    throw new Error(`Missing environment variables: ${missing.join(', ')}.`);
  }
  return {
    supabaseUrl: validateUrl(values.SUPABASE_URL),
    supabasePublishableKey: validatePublishableKey(values.SUPABASE_PUBLISHABLE_KEY),
  };
}

function generateEnvironment({ root, environment = process.env, strict = false }) {
  const vercelBuild = environment.VERCEL === '1' || Boolean(environment.VERCEL_ENV);
  const local = vercelBuild ? {} : readLocalEnvironment(path.join(root, '.env.local'));
  const config = resolveEnvironment(environment, local, strict || vercelBuild);
  const target = path.join(root, GENERATED_PATH);
  const source = [
    '// Generated by scripts/generate-environment.cjs. Public browser configuration only.',
    `export const environment = ${JSON.stringify(config, null, 2)} as const;`,
    '',
  ].join('\n');
  fs.mkdirSync(path.dirname(target), { recursive: true });
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== source) {
    fs.writeFileSync(target, source, 'utf8');
  }
  return config;
}

if (require.main === module) {
  try {
    const config = generateEnvironment({
      root: path.resolve(__dirname, '..'),
      strict: process.argv.includes('--strict'),
    });
    console.log(
      config.supabaseUrl
        ? 'Public Supabase environment generated; values omitted.'
        : 'Supabase is unconfigured locally; landing remains available, auth is disabled.',
    );
  } catch (error) {
    console.error(`Environment configuration failed: ${error.message}`);
    process.exitCode = 1;
  }
}

module.exports = {
  generateEnvironment,
  readLocalEnvironment,
  resolveEnvironment,
  validatePublishableKey,
  validateUrl,
};
